const dictionaries: Record<EditorLocale, Record<MessageKey, string>> = { en, "zh-CN": zhCN };

function detectLocale(): EditorLocale {
	const lang = typeof navigator !== "undefined" ? navigator.language : "";
	return lang && lang.toLowerCase().startsWith("zh") ? "zh-CN" : "en";
}

function initialLocale(): EditorLocale {
	const docLang = typeof document !== "undefined" ? document.documentElement.lang : "";
	return docLang === "zh-CN" || docLang === "en" ? docLang : detectLocale();
}

export const editorLocale = ref<EditorLocale>(initialLocale());

export function t(key: MessageKey, params?: Record<string, string | number>): string {
	const table = dictionaries[editorLocale.value] ?? dictionaries.en;
	let text = table[key] ?? dictionaries.en[key] ?? key;
	if (params) {
		for (const [name, value] of Object.entries(params)) {
			text = text.replaceAll(`{${name}}`, String(value));
		}
	}
	return text;
}

/** Plural helper: English switches one/many; zh-CN uses a single form. */
export function tp(one: MessageKey, many: MessageKey, count: number, params: Record<string, string | number> = {}): string {
	const key = editorLocale.value === "en" && count === 1 ? one : many;
	return t(key, { ...params, count });
}

export function setEditorLocale(locale: EditorLocale): void {
	editorLocale.value = locale;
	if (typeof document !== "undefined") document.documentElement.lang = locale;
}

/**
 * Imperative translation pass for DOM regions Vue does not own (the v-once
 * legacy stack-editor chrome). Elements opt in with data-i18n (textContent)
 * and data-i18n-title (title attribute).
 */
export function translateDom(root: ParentNode): void {
	for (const element of root.querySelectorAll<HTMLElement>("[data-i18n]")) {
		element.textContent = t(element.dataset.i18n as MessageKey);
	}
	for (const element of root.querySelectorAll<HTMLElement>("[data-i18n-title]")) {
		element.title = t(element.dataset.i18nTitle as MessageKey);
	}
	for (const element of root.querySelectorAll<HTMLElement>("[data-i18n-aria]")) {
		element.setAttribute("aria-label", t(element.dataset.i18nAria as MessageKey));
	}
}
