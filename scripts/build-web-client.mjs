import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import process from "node:process";
import vue from "@vitejs/plugin-vue";
import { build } from "vite";

const root = resolve(import.meta.dirname, "..");
const entryPoint = resolve(root, "src/web-editor/client/main.ts");
const scriptOutputPath = resolve(root, "src/web-editor/client-script.generated.ts");
const stylesOutputPath = resolve(root, "src/web-editor/client-styles.generated.ts");
const check = process.argv.includes("--check");

const result = await build({
	root,
	configFile: false,
	publicDir: false,
	logLevel: "silent",
	plugins: [vue()],
	define: {
		"process.env.NODE_ENV": JSON.stringify("production"),
		__VUE_OPTIONS_API__: "false",
		__VUE_PROD_DEVTOOLS__: "false",
		__VUE_PROD_HYDRATION_MISMATCH_DETAILS__: "false",
	},
	build: {
		write: false,
		target: "es2022",
		minify: false,
		cssCodeSplit: false,
		lib: {
			entry: entryPoint,
			name: "PiForgeEditor",
			formats: ["iife"],
			fileName: () => "pi-forge-editor.js",
			cssFileName: "pi-forge-editor",
		},
		rollupOptions: {
			output: {
				entryFileNames: "pi-forge-editor.js",
				assetFileNames: "pi-forge-editor.[ext]",
			},
		},
	},
});
const outputs = (Array.isArray(result) ? result : [result]).flatMap((buildResult) => buildResult.output);
const chunks = outputs.filter((output) => output.type === "chunk");
const assets = outputs.filter((output) => output.type === "asset");
if (chunks.length !== 1 || !chunks[0]?.isEntry) {
	throw new Error(`Vite must produce exactly one entry chunk; received ${chunks.length} chunks.`);
}
const unsupportedAssets = assets.filter((asset) => !asset.fileName.endsWith(".css"));
if (unsupportedAssets.length > 0) {
	throw new Error(`Vite produced unsupported web editor assets: ${unsupportedAssets.map((asset) => asset.fileName).join(", ")}`);
}
if (assets.filter((asset) => asset.fileName.endsWith(".css")).length > 1) {
	throw new Error("Vite must produce at most one web editor CSS asset.");
}

const script = chunks[0].code;
const cssAsset = assets.find((asset) => asset.fileName.endsWith(".css"));
const styles = cssAsset ? outputText(cssAsset.source) : "";
const generatedScript = generatedModule("EDITOR_CLIENT_SCRIPT", script);
const generatedStyles = generatedModule("EDITOR_CLIENT_STYLES", styles);

if (check) {
	const stale = [
		[scriptOutputPath, generatedScript],
		[stylesOutputPath, generatedStyles],
	].filter(([path, expected]) => readGenerated(path) !== expected);
	if (stale.length > 0) {
		console.error("The generated web editor assets are stale. Run: npm run build:client");
		process.exitCode = 1;
	} else {
		console.log("Generated web editor JavaScript and CSS are synchronized with typed Vue source.");
	}
} else {
	writeFileSync(scriptOutputPath, generatedScript, "utf8");
	writeFileSync(stylesOutputPath, generatedStyles, "utf8");
	console.error(`Bundled typed web editor assets to ${scriptOutputPath} and ${stylesOutputPath}.`);
}

function generatedModule(name, value) {
	return `// Generated by scripts/build-web-client.mjs. Do not edit.\nexport const ${name}: string = ${JSON.stringify(value)};\n`;
}

function readGenerated(path) {
	try {
		return readFileSync(path, "utf8");
	} catch {
		return "";
	}
}

function outputText(source) {
	return typeof source === "string" ? source : Buffer.from(source).toString("utf8");
}
