import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import process from "node:process";
import { build } from "esbuild";

const root = resolve(import.meta.dirname, "..");
const entryPoint = resolve(root, "src/web-editor/client/main.ts");
const outputPath = resolve(root, "src/web-editor/client-script.generated.ts");
const check = process.argv.includes("--check");

const result = await build({
	entryPoints: [entryPoint],
	bundle: true,
	write: false,
	platform: "browser",
	format: "iife",
	target: "es2022",
	charset: "utf8",
	legalComments: "none",
	minify: false,
	logLevel: "silent",
});
const script = result.outputFiles[0]?.text;
if (!script) throw new Error("esbuild did not produce the web editor client bundle.");
const generated = `// Generated by scripts/build-web-client.mjs. Do not edit.\nexport const EDITOR_CLIENT_SCRIPT = ${JSON.stringify(script)};\n`;

if (check) {
	let current = "";
	try {
		current = readFileSync(outputPath, "utf8");
	} catch {
		// Report the same actionable consistency error for a missing file.
	}
	if (current !== generated) {
		console.error("The generated web editor client is stale. Run: npm run build:client");
		process.exitCode = 1;
	} else {
		console.log("Generated web editor client is synchronized with typed source modules.");
	}
} else {
	writeFileSync(outputPath, generated, "utf8");
	console.error(`Bundled typed web editor client to ${outputPath}.`);
}
